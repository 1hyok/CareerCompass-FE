package com.careercompass.careercompass_fe.session

/**
 * 세션이 **어떻게** 끝났는가 — 화면이 앱 셸에 실어 보내는 사유.
 *
 * 설명이 필요한 쪽은 만료뿐이다. 로그아웃은 사용자가 방금 누른 결과라 로그인 화면이 덧붙일 말이 없고,
 * 「앱이 이유 없이 로그아웃시켰다」로 보이는 것은 만료다 — 기능 스펙 F1-1 이 명시적 로그아웃 전까지 재로그인을
 * 요구하지 않겠다고 약속했기 때문에 더 그렇다.
 *
 * 한 번의 재계산에 둘이 겹치면 [LoggedOut] 이 이긴다([MainViewModel]). 로그아웃 요청이 나간 뒤 남아 있던 요청이
 * 401 을 물고 돌아오는 순서가 실제로 있어서, 사용자가 스스로 끝낸 세션에 만료 안내가 붙지 않게 한다.
 */
public enum class SessionEndCause {
    /** 서버가 401 로 세션을 끝냈다 — 피드·상세·게시판, 그리고 셸 자신의 세션 진입 판정. */
    Expired,

    /** 사용자가 마이 탭에서 로그아웃했다. */
    LoggedOut,
}
